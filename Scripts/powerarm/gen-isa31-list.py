"""Classify every PPC64 emitter instruction at ISA 3.1 (-mpower10 vs -mpower9).

   gen-isa31-list.py OUT_ISA31 OUT_UNCLASSIFIED

Uses the GNU ppc64le assembler (POWERARM_PPC64_AS, powerpc64le-unknown-linux-gnu-as,
or /mnt/arch/usr/bin/as) to find every emitter method accepted at -mpower10 and
rejected at -mpower9.
"""
import io, os, re, shutil, subprocess, sys

AS = (
    os.environ.get("POWERARM_PPC64_AS")
    or shutil.which("powerpc64le-linux-gnu-as")
    or shutil.which("powerpc64le-unknown-linux-gnu-as")
    or ("/mnt/arch/usr/bin/as" if os.path.exists("/mnt/arch/usr/bin/as") else None)
    or "/home/jbettcher/Development/FPGA_PPC/toolchains/bin/powerpc64le-linux-gnu-as"
)

em = io.open("CodeEmitter/PPC64LE/Emitter.h", encoding="utf-8").read()
methods = sorted(set(re.findall(r'^\s*(?:\[\[[^\]]*\]\]\s*)?void\s+([A-Za-z_][A-Za-z0-9_]*)\s*\(', em, re.M)))


def mnem(m):
    return m[:-1] + "." if m.endswith("_") else m


T = [
    "3,4,5", "3,4", "32,33,34", "32,33", "2,3,4", "2,3", "3,2", "32,0(3)", "3,0(4)",
    "3,4,5,6", "2,3,4,5", "32,3,4", "3,32", "32,3", "32,0", "3,4,5,6,7", "2,3,4,1",
    "0", "3,0", "3", "", "2,3,4,0", "32,33,34,0", "32,33,34,35", "32,33,34,35,0",
    "32,33,0", "1,3,4", "3,4,0,0", "3,4,0,31", "2,0,3", "32,0,3", "3,0,4", "2,3,0",
]

cands = []
for M in methods:
    mn = mnem(M)
    if not re.match(r'^[a-z][a-z0-9_.]*$', mn):
        continue
    for t in T:
        cands.append((mn, (mn + " " + t).strip()))


def run(level, lines):
    src = "\n".join(lines) + "\n"
    p = subprocess.run([AS, "-m" + level, "-o", "/dev/null", "-"],
                       input=src.encode(), capture_output=True)
    bad = set()
    for L in p.stderr.decode(errors="replace").split("\n"):
        m = re.search(r':(\d+): (?:Error|Fatal)', L)
        if m:
            bad.add(int(m.group(1)))
    return bad


bad10 = run("power10", [c[1] for c in cands])
ok10_forms = {}
for i, (mn, txt) in enumerate(cands, start=1):
    if i not in bad10:
        ok10_forms.setdefault(mn, []).append(txt)

flat10 = [(mn, txt) for mn in sorted(ok10_forms) for txt in ok10_forms[mn]]
bad9 = run("power9", [txt for _, txt in flat10])
ok9_mnems = set(mn for i, (mn, _) in enumerate(flat10, start=1) if i not in bad9)
isa31 = sorted(set(ok10_forms) - ok9_mnems)
unresolved = sorted(set(mnem(M) for M in methods
                        if re.match(r'^[a-z][a-z0-9_.]*$', mnem(M))) - set(ok10_forms))

print("emitter methods with a mnemonic: %d" % len(set(mnem(M) for M in methods if re.match(r'^[a-z][a-z0-9_.]*$', mnem(M)))))
print("classified (a form assembled at power10): %d" % len(ok10_forms))
print("ISA 3.1 (rejected at power9): %d" % len(isa31))
print("no operand template matched (unclassified): %d" % len(unresolved))
header = (
    "# ISA 3.1 instructions the PPC64 emitter can produce.\n"
    "# GENERATED by Scripts/powerarm/gen-isa31-list.py -- do not hand-edit.\n"
    "# Oracle: GNU ppc64le assembler, -mpower9 vs -mpower10.\n"
)
io.open(sys.argv[1], "w").write(header + "\n".join(isa31) + "\n")
io.open(sys.argv[2], "w").write("\n".join(unresolved) + "\n")
print()
print("ISA 3.1:", " ".join(isa31))
