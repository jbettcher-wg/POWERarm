"""Find ISA 3.0 instructions emitted on paths that run without ISA 3.0.

WHY THIS EXISTS. POWERarm gates ISA 3.0 lowerings on HostFeatures.SupportsISA30,
read at startup from AT_HWCAP2, so one binary serves POWER8 and POWER9. An ISA
3.0 instruction that escapes such a guard is invisible here in every way that
normally catches things:

  * it builds -- `clang -mcpu=power8` assembles `lxv` without complaint, and
    llvm-objdump decodes it happily at --mcpu=pwr8, so neither tool is an oracle;
  * it runs on this box, because this box IS a POWER9;
  * it passes POWERARM_HOSTFEATURES=disableisa30, because that flips the feature
    FLAG and exercises the POWER8 code PATH on POWER9 HARDWARE -- the instruction
    still executes.

It traps only on a real POWER8, i.e. only at a user. So the check has to be
static, and this is it.

WHAT IT CHECKS. For each known ISA 3.0 emitter method, every call site in the
PPC64LE backend must be inside a function that consults SupportsISA30 (or an
ISA30-named helper, or is itself only reachable from one). A call in a function
with no such mention is reported.

WHAT IT CANNOT CHECK. Guard *correctness* -- that the call sits on the true arm
rather than the false one -- is not decidable by this, and neither is reachability
through a helper that takes the flag as an argument. Those are listed as
reviewed-by-hand exemptions below, each with a reason, rather than silently
skipped. This is a lint that catches the easy mistake, not a proof.
"""
import re, sys, os, io, collections

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
# Everywhere that emits PPC64 instructions. ArchHelpers/PPC64Emitter.cpp is the
# second one and was missed on the first pass -- it emits lxv/stxv and the
# byte/halfword VSX load-stores, so leaving it out made the check look complete
# while being blind to six ISA 3.0 instructions.
SCAN = [
    os.path.join(ROOT, "FEXCore/Source/Interface/Core/JIT/PPC64LE"),
    os.path.join(ROOT, "FEXCore/Source/Interface/Core/ArchHelpers"),
]

# The ISA 3.0 set is generated by Scripts/powerarm/gen-isa30-list.py, which asks
# the HOST's ppc64le GNU assembler (the only thing on this box that enforces
# -mpower8 vs -mpower9) to classify every emitter instruction. Regenerate it when
# the emitter gains instructions; do not hand-edit it. Hand-classifying this is
# what produced six false findings on the first attempt.
LIST = os.path.join(ROOT, "Scripts/powerarm/isa30-instructions.txt")
if not os.path.exists(LIST):
    print("FAIL %s is missing; regenerate with gen-isa30-list.py" % LIST, file=sys.stderr)
    sys.exit(2)
with io.open(LIST, encoding="utf-8") as f:
    ISA30_MNEM = sorted(x.strip() for x in f if x.strip() and not x.startswith("#"))
# Emitter METHOD names: the ISA's trailing `.` is a trailing `_` in the emitter.
ISA30 = sorted(set(m[:-1] + "_" if m.endswith(".") else m for m in ISA30_MNEM))

# Reviewed by hand; each needs a reason, and an empty reason is a failure.
EXEMPT = {
    # (method, enclosing function): reason
}

# Named predicates that ARE the flag, as well as the flag itself.
# ProjectXERUsesMcrxrx() is `return HostFeatures.SupportsISA30` (JIT.cpp:994).
GUARD = re.compile(r'SupportsISA30|HostSupportsISA30|ISA30\b|Isa30|isa30'
                   r'|ProjectXERUsesMcrxrx')
# A function definition at column 0: DEF_OP(...), DEF_OP_VSX(...), or a plain
# definition. Good enough to attribute a call to an enclosing body.
# What counts as a function definition. This has to cope with three shapes, and
# getting it wrong is how the check goes quietly blind rather than loudly wrong:
#
#   DEF_OP(Foo) {                                 the JIT's op handlers
#   void PPC64EmitterBase::EmitLoad(...) {        out-of-line methods
#     void EmitLoadPPC64VConst(...) {             INDENTED inline class methods
#
# The first version anchored at column 0 and had no `::`, so it parsed zero
# bodies from ArchHelpers/PPC64Emitter.cpp and missed the inline methods in
# JITClass.h -- while still reporting a healthy body count from elsewhere in the
# same files. The audit in main() exists because of that, and it caught the second
# of those two misses after the first was fixed.
#
# A definition is TYPE then NAME then `(`, so a bare call (`lxv(dst, ...)`) has no
# type and does not match; a leading control keyword is excluded; and any `=` or
# `;` before the paren means it is a declaration or an expression, not a head.
KEYWORDS = r'if|for|while|switch|return|else|do|case|catch|sizeof|assert|static_assert'
FUNCDEF_RE = re.compile(r'^(\s*)(?:DEF_OP[A-Z_]*\s*\(|(?!(?:' + KEYWORDS + r')\b)'
                        r'[A-Za-z_][A-Za-z0-9_:<>,\*& ]*?\s+[A-Za-z_][A-Za-z0-9_:~]*\s*\()')

def FUNCDEF_match(line):
    m = FUNCDEF_RE.match(line)
    if not m:
        return None
    head = line[:m.end()]
    if "=" in head or ";" in head:
        return None
    return m

def functions(path):
    """Yield (name, text) for each column-0 function body."""
    lines = io.open(path, encoding="utf-8", errors="replace").read().split("\n")
    cur_name, cur, depth, started = None, [], 0, False
    for L in lines:
        if not started and FUNCDEF_match(L):
            cur_name = L.strip()[:90]
            cur, depth, started = [L], L.count("{") - L.count("}"), "{" in L
            if started and depth <= 0:
                yield cur_name, "\n".join(cur)
                cur_name, cur, depth, started = None, [], 0, False
            continue
        if cur_name is not None:
            cur.append(L)
            if not started:
                depth += L.count("{") - L.count("}")
                started = "{" in L
            else:
                depth += L.count("{") - L.count("}")
            if started and depth <= 0:
                yield cur_name, "\n".join(cur)
                cur_name, cur, depth, started = None, [], 0, False

def strip_noncode(line):
    """Drop // comments and string literals, keeping column positions irrelevant."""
    out, i, n = [], 0, len(line)
    in_str = None
    while i < n:
        c = line[i]
        if in_str:
            if c == "\\":
                i += 2
                continue
            if c == in_str:
                in_str = None
            i += 1
            continue
        if c in ('"', "'"):
            in_str = c
            i += 1
            continue
        if c == "/" and i + 1 < n and line[i + 1] == "/":
            break
        out.append(c)
        i += 1
    return "".join(out)


def enclosing_guarded(body, call_line_idx):
    """Is the call lexically inside a block whose `if` mentions ISA30?

    Walks the body keeping a stack of the lines that opened each live block, so
    the `if (ISA30) { ... }` and `if (!ISA30) { ...; return; }` shapes are both
    visible. Returns (inside_guard, saw_negated_early_return_before).
    """
    lines = [strip_noncode(x) for x in body.split("\n")]
    stack = []
    pending = ""
    negated_return_before = False
    for i, L in enumerate(lines):
        if i == call_line_idx:
            return (any(GUARD.search(t) for t in stack), negated_return_before)
        for ch in L:
            if ch == "{":
                stack.append(pending + " " + L)
            elif ch == "}":
                if stack:
                    top = stack.pop()
                    # `if (!ISA30) { ... return; }` leaves the rest of the
                    # function reachable only with ISA 3.0, which is safe.
                    if GUARD.search(top) and "!" in top and "return" in top:
                        negated_return_before = True
        pending = L
    return (False, negated_return_before)


def main():
    calls = {m: re.compile(r'(?<![A-Za-z0-9_])' + re.escape(m) + r'\s*\(') for m in ISA30}
    hard, review = [], []
    scanned = 0
    files = []
    for d in SCAN:
        if not os.path.isdir(d):
            continue
        for fn in sorted(os.listdir(d)):
            if fn.endswith((".cpp", ".h")) and "PPC64" in fn or (
                    fn.endswith((".cpp", ".h")) and d.endswith("PPC64LE")):
                files.append((fn, os.path.join(d, fn)))
    blind = []
    for fn, path in files:
        text = io.open(path, encoding="utf-8", errors="replace").read()
        text_hits = sum(1 for m in ISA30
                        if re.search(r'(?<![A-Za-z0-9_])' + re.escape(m) + r'\s*\(', text))
        body_count = 0
        covered = 0
        for name, body in functions(path):
            body_count += 1
            covered += sum(1 for m in ISA30
                           if re.search(r'(?<![A-Za-z0-9_])' + re.escape(m) + r'\s*\(', body))
        if text_hits and not covered:
            blind.append((fn, text_hits, body_count))
    for fn, path in files:
        for name, body in functions(path):
            scanned += 1
            mentions = bool(GUARD.search(body))
            # Strip // comments and string literals before matching: a comment
            # saying "on ISA 3.0 this is native xxbrw" is not a call, and
            # reporting it is how a lint earns being ignored.
            blines = [strip_noncode(x) for x in body.split("\n")]
            for m, rx in calls.items():
                for i, L in enumerate(blines):
                    if not rx.search(L):
                        continue
                    key = (m, name)
                    if key in EXEMPT:
                        continue
                    if not mentions:
                        hard.append((fn, name, m, i))
                        continue
                    inside, neg_ret = enclosing_guarded(body, i)
                    if not inside and not neg_ret:
                        review.append((fn, name, m, L.strip()[:72]))
    print("# ISA 3.0 guard lint: %d ISA 3.0 emitters (generated list), %d function bodies in %s"
          % (len(ISA30), scanned, ", ".join(os.path.relpath(d, ROOT) for d in SCAN)))
    rc = 0
    if blind:
        # A file whose ISA 3.0 calls fall outside every parsed body is not a
        # clean file, it is an unexamined one, and saying "ok" about it is worse
        # than saying nothing.
        print("FAIL the parser sees ISA 3.0 calls in %d file(s) but captured none of them in a"
              " function body -- these were NOT checked:" % len(blind))
        for fn, hits, bodies in blind:
            print("  %-26s %d ISA 3.0 mnemonic(s) in the text, %d bodies parsed" % (fn, hits, bodies))
        print("  Fix FUNCDEF so those definitions parse; do not ignore this.")
        rc = 1
    if hard:
        print("FAIL %d ISA 3.0 call(s) in a function that never consults SupportsISA30:" % len(hard))
        for fn, name, m, _ in sorted(hard):
            print("  %-22s %-56s %s" % (fn, name, m))
        rc = 1
    else:
        print("ok   tier 1: every ISA 3.0 call is in a function that consults SupportsISA30")
    if review:
        print("REVIEW %d ISA 3.0 call(s) whose function consults the flag but which are not"
              " lexically inside a guarded block:" % len(review))
        for fn, name, m, src in sorted(review):
            print("  %s\n    %s\n    %s   <- %s" % (fn, name, src, m))
        print()
        print("  Not necessarily wrong -- a helper taking the flag as a parameter, or an")
        print("  `if (!ISA30) { ...; return; }` earlier in a DIFFERENT block, both land here.")
        print("  Each needs an EXEMPT entry with a reason once reviewed.")
    else:
        print("ok   tier 2: every ISA 3.0 call is inside a block guarded on the flag")
    return rc


sys.exit(main())
